-- Grant permissions to web_anon role for PostgREST access

GRANT USAGE ON SCHEMA ${example} TO web_anon;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA ${example} TO web_anon;
ALTER DEFAULT PRIVILEGES IN SCHEMA ${example} GRANT SELECT, INSERT, UPDATE ON TABLES TO web_anon;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA ${example} TO web_anon;
ALTER DEFAULT PRIVILEGES IN SCHEMA ${example} GRANT EXECUTE ON FUNCTIONS TO web_anon;
